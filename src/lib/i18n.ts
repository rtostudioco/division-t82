const dicts = { es, en }

export function useI18n() {
  const lang = useAppStore((s) => s.lang)
  const setLang = useAppStore((s) => s.setLang)
  const t = (key: I18nKey): string => dicts[lang][key] ?? key
  return { t, lang, setLang }
}

export function localized(value: { en: string; es: string } | null | undefined, lang: 'es' | 'en'): string {
  if (!value) return ''
  return value[lang] ?? value.en
}
